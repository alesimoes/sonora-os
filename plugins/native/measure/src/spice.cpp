const char* law_name(dsp::TriodeLaw law) { return law == dsp::TriodeLaw::Dempwolf ? "dempwolf" : "koren"; }

std::vector<SpiceCase> triode_spice_cases() {
    std::vector<SpiceCase> v;
    // 0.25 V: clean, the harmonics 40 dB down and more; 1 V: the grid
    // swings to within 0.2 V of the cathode; 2 and 4 V: grid current and
    // cut-off, the bias shifted through Cin.
    for (double f : {100.0, 1000.0, 5000.0})
        for (double a : {0.25, 1.0, 2.0, 4.0}) v.push_back({dsp::TriodeLaw::Dempwolf, a, f});
    for (double a : {0.25, 1.0, 2.0, 4.0}) v.push_back({dsp::TriodeLaw::Koren, a, 1000.0});
    return v;
}

std::string spice_case_name(const SpiceCase& c) {
    char b[64];
    std::snprintf(b, sizeof b, "%s-%gv-%ghz", law_name(c.law), c.amplitude_v, c.freq_hz);
    return b;
}

std::string triode_netlist(const SpiceCase& c, const SpiceTiming& t, const dsp::TriodeStageCircuit& k,
                           const dsp::TriodeDevice& d) {
    std::ostringstream n;
    n << "* Sonora SPICE reference: common-cathode triode stage, " << spice_case_name(c) << "\n"
      << "* Generated by sonora-dsp-measure --spice-generate from common/dsp/triode.h;\n"
      << "* do not edit (plugins/native/measure/include/sonora/measure/spice.h).\n"
      << "VIN in 0 SIN(0 " << sp(c.amplitude_v) << " " << sp(c.freq_hz) << ")\n"
      << "VBP bp 0 DC " << sp(k.supply_v) << "\n"
      << "CIN in a " << sp(k.c_in) << "\n"
      << "RLEAK a 0 " << sp(k.r_leak) << "\n"
      << "RGRID a g " << sp(k.r_grid) << "\n"
      << "RK k 0 " << sp(k.r_cathode) << "\n"
      << "CK k 0 " << sp(k.c_cathode) << "\n"
      << "RP bp p " << sp(k.r_plate) << "\n"
      << "COUT p o " << sp(k.c_out) << "\n"
      << "RL o 0 " << sp(k.r_load) << "\n"
      << "CGK g k " << sp(d.c_gk) << "\n"
      << "CGP g p " << sp(d.c_gp) << "\n"
      << "CPK p k " << sp(d.c_pk) << "\n";
    if (c.law == dsp::TriodeLaw::Dempwolf) {
        // Dempwolf and Zolzer, DAFx-11, eqs. (10)-(12).
        const std::string ig = sp(d.gg) + "*pow(ln(1+exp(" + sp(d.cg) + "*v(g,k)))/" + sp(d.cg) + "," + sp(d.xi) +
                               ")+" + sp(d.ig0);
        n << "BIP p k I=" << sp(d.g) << "*pow(ln(1+exp(" << sp(d.c) << "*(v(p,k)/" << sp(d.mu) << "+v(g,k))))/"
          << sp(d.c) << "," << sp(d.gamma) << ")-(" << ig << ")\n"
          << "BIG g k I=" << ig << "\n";
    } else {
        // Koren, Glass Audio 1996, eq. (4); grid current through RGI above
        // 0 V. ngspice's exp() limits its argument, so the softplus is
        // written in its overflow-free form, as the model evaluates it.
        const std::string x = sp(d.k_kp) + "*(1/" + sp(d.k_mu) + "+v(g,k)/sqrt(" + sp(d.k_kvb) + "+v(p,k)*v(p,k)))";
        const std::string spl = "(max(" + x + ",0)+ln(1+exp(-abs(" + x + "))))";
        const std::string e1 = "(v(p,k)/" + sp(d.k_kp) + "*" + spl + ")";
        n << "BIP p k I=(" << e1 << ">0)?(2*pow(" << e1 << "," << sp(d.k_ex) << ")/" << sp(d.k_kg1) << "):0\n"
          << "BIG g k I=(v(g,k)>0)?(v(g,k)/" << sp(d.k_rgi) << "):0\n";
    }
    n << ".options reltol=1e-7 abstol=1e-15 vntol=1e-10 method=trap\n"
      << ".control\n"
      << "op\n"
      << "wrdata op.txt v(a) v(g) v(k) v(p)\n"
      // Output from two steps before the window, so its first point is
      // inside it rather than after it.
      << "tran " << sp(max_step(c)) << " " << sp(t.settle_s + t.window_s) << " "
      << sp(t.settle_s - 2.0 * max_step(c)) << " "
      << sp(max_step(c)) << "\n"
      << "wrdata out.txt v(o)\n"
      << ".endc\n"
      << ".end\n";
    return n.str();
}

bool spice_harmonics(const std::string& path, double f0, double t0, double t1, Harmonics& out, std::string& error) {
    std::ifstream f(path);
    if (!f) {
        error = "cannot read " + path;
        return false;
    }
    std::vector<double> t, v;
    double a, b;
    while (f >> a >> b) {
        t.push_back(a);
        v.push_back(b);
    }
    if (t.size() < 100 || t.front() > t0 + 1e-9 || t.back() < t1 - 1e-9) {
        error = "ngspice output " + path + " does not cover the window";
        return false;
    }
    out.assign(kSpiceHarmonics, {0.0, 0.0});
    const auto value_at = [&](std::size_t i, double tt) {
        const double s = (v[i + 1] - v[i]) / (t[i + 1] - t[i]);
        return v[i] + s * (tt - t[i]);
    };
    for (std::size_t i = 0; i + 1 < t.size(); ++i) {
        double ta = t[i], tb = t[i + 1];
        if (tb <= t0 || ta >= t1 || tb <= ta) continue;
        double va = v[i], vb = v[i + 1];
        if (ta < t0) {
            va = value_at(i, t0);
            ta = t0;
        }
        if (tb > t1) {
            vb = value_at(i, t1);
            tb = t1;
        }
        const double s = (vb - va) / (tb - ta);
        for (std::uint32_t k = 1; k <= kSpiceHarmonics; ++k) {
            // The piecewise-linear waveform against e^{-jwt}, exactly:
            // (vb eb - va ea) / (-jw) + s (eb - ea) / w^2.
            const double w = dsp::kTwoPi * f0 * k;
            const std::complex<double> ea = std::polar(1.0, -w * ta), eb = std::polar(1.0, -w * tb);
            out[k - 1] += (vb * eb - va * ea) / std::complex<double>(0.0, -w) + s * (eb - ea) / (w * w);
        }
    }
    for (auto& c : out) c *= 2.0 / (t1 - t0);
    return true;
}

Harmonics sampled_harmonics(const std::vector<double>& y, double fs, double f0, std::size_t from, std::size_t count) {
    Harmonics out(kSpiceHarmonics, {0.0, 0.0});
    for (std::uint32_t k = 1; k <= kSpiceHarmonics; ++k) {
        const double w = dsp::kTwoPi * f0 * k / fs;
        std::complex<double> acc = 0.0;
        for (std::size_t n = from; n < from + count; ++n) acc += y[n] * std::polar(1.0, -w * static_cast<double>(n));
        out[k - 1] = acc * (2.0 / static_cast<double>(count));
    }
    return out;
}

Harmonics model_harmonics(const SpiceCase& c, const SpiceTiming& t, double rate, const dsp::TriodeStageCircuit& circuit,
                          const dsp::TriodeDevice& device, bool tabulated, std::uint32_t* max_iterations) {
    dsp::TriodeStage stage;
    if (!stage.prepare(rate, c.law, circuit, device, tabulated)) return {};
    const auto from = static_cast<std::size_t>(std::llround(t.settle_s * rate));
    const auto count = static_cast<std::size_t>(std::llround(t.window_s * rate));
    std::vector<double> y(from + count);
    for (std::size_t n = 0; n < y.size(); ++n) {
        const double vin = c.amplitude_v * std::sin(dsp::kTwoPi * c.freq_hz * static_cast<double>(n) / rate);
        y[n] = stage.tick(vin);
    }
    if (max_iterations != nullptr) *max_iterations = stage.max_iterations_seen();
    return sampled_harmonics(y, rate, c.freq_hz, from, count);
}

json::Value circuit_json(const dsp::TriodeStageCircuit& c) {
    json::Value o = json::Value::object();
    o.set("supply_v", jnum(c.supply_v));
    o.set("r_plate", jnum(c.r_plate));
    o.set("r_cathode", jnum(c.r_cathode));
    o.set("c_cathode", jnum(c.c_cathode));
    o.set("c_in", jnum(c.c_in));
    o.set("r_leak", jnum(c.r_leak));
    o.set("r_grid", jnum(c.r_grid));
    o.set("c_out", jnum(c.c_out));
    o.set("r_load", jnum(c.r_load));
    return o;
}

json::Value device_json(const dsp::TriodeDevice& d) {
    json::Value o = json::Value::object();
    const std::pair<const char*, double> v[] = {
        {"g", d.g},         {"mu", d.mu},       {"gamma", d.gamma}, {"c", d.c},         {"gg", d.gg},
        {"xi", d.xi},       {"cg", d.cg},       {"ig0", d.ig0},     {"k_mu", d.k_mu},   {"k_ex", d.k_ex},
        {"k_kg1", d.k_kg1}, {"k_kp", d.k_kp},   {"k_kvb", d.k_kvb}, {"k_rgi", d.k_rgi}, {"c_gk", d.c_gk},
        {"c_gp", d.c_gp},   {"c_pk", d.c_pk},
    };
    for (const auto& kv : v) o.set(kv.first, jnum(kv.second));
    return o;
}

bool read_spice_reference(const std::string& path, SpiceReference& ref, std::string& error) {
    std::string text;
    if (!read_file(path, text)) {
        error = "cannot read " + path;
        return false;
    }
    json::Value root;
    json::Error e;
    if (!json::parse(text, root, e)) {
        error = path + ": " + e.message;
        return false;
    }
    const json::Value* ng = root.find("ngspice");
    const json::Value* timing = root.find("timing");
    const json::Value* cases = root.find("cases");
    const json::Value* circuit = root.find("circuit");
    const json::Value* device = root.find("device");
    if (ng == nullptr || timing == nullptr || cases == nullptr || circuit == nullptr || device == nullptr ||
        !cases->is_array()) {
        error = path + ": missing fields";
        return false;
    }
    ref.ngspice = ng->text();
    ref.timing.settle_s = get(*timing, "settle_s");
    ref.timing.window_s = get(*timing, "window_s");
    ref.circuit = *circuit;
    ref.device = *device;
    for (const json::Value& c : cases->items()) {
        const json::Value* law = c.find("law");
        const json::Value* re = c.find("re");
        const json::Value* im = c.find("im");
        const json::Value* op = c.find("op");
        if (law == nullptr || re == nullptr || im == nullptr || op == nullptr ||
            re->items().size() != kSpiceHarmonics || im->items().size() != kSpiceHarmonics) {
            error = path + ": malformed case";
            return false;
        }
        SpiceCase sc{law->text() == "koren" ? dsp::TriodeLaw::Koren : dsp::TriodeLaw::Dempwolf,
                     get(c, "amplitude_v"), get(c, "freq_hz")};
        Harmonics h(kSpiceHarmonics);
        for (std::uint32_t k = 0; k < kSpiceHarmonics; ++k) {
            double r = 0.0, i = 0.0;
            re->items()[k].to_double(r);
            im->items()[k].to_double(i);
            h[k] = {r, i};
        }
        std::vector<double> o;
        for (const json::Value& x : op->items()) {
            double d = 0.0;
            x.to_double(d);
            o.push_back(d);
        }
        ref.cases.push_back(sc);
        ref.harmonics.push_back(h);
        ref.op.push_back(o);
    }
    return true;
}

int spice_generate(const std::string& dir, const std::string& ngspice, const std::string& work) {
    const dsp::TriodeStageCircuit circuit;
    const dsp::TriodeDevice device;
    const SpiceTiming timing;
    json::Value root = json::Value::object();
    root.set("generator", json::Value::string("sonora-dsp-measure --spice-generate"));
    root.set("ngspice", json::Value::string(ngspice_version(ngspice, work)));
    json::Value tj = json::Value::object();
    tj.set("settle_s", jnum(timing.settle_s));
    tj.set("window_s", jnum(timing.window_s));
    root.set("timing", tj);
    root.set("circuit", circuit_json(circuit));
    root.set("device", device_json(device));
    json::Value cases = json::Value::array();
    for (const SpiceCase& c : triode_spice_cases()) {
        const std::string name = spice_case_name(c);
        const std::string netlist = triode_netlist(c, timing, circuit, device);
        if (!write_file(dir + "/" + name + ".cir", netlist)) {
            std::fprintf(stderr, "cannot write %s/%s.cir\n", dir.c_str(), name.c_str());
            return 1;
        }
        std::string err;
        Harmonics h;
        std::vector<double> op;
        if (!run_ngspice(ngspice, work, netlist, err) || !read_op(work + "/op.txt", op, err) ||
            !spice_harmonics(work + "/out.txt", c.freq_hz, timing.settle_s, timing.settle_s + timing.window_s, h,
                             err)) {
            std::fprintf(stderr, "%s: %s\n", name.c_str(), err.c_str());
            return 1;
        }
        json::Value o = json::Value::object();
        o.set("name", json::Value::string(name));
        o.set("law", json::Value::string(law_name(c.law)));
        o.set("amplitude_v", jnum(c.amplitude_v));
        o.set("freq_hz", jnum(c.freq_hz));
        json::Value opj = json::Value::array();
        for (double x : op) opj.push(jnum(x));
        o.set("op", opj);
        json::Value re = json::Value::array(), im = json::Value::array();
        for (const auto& z : h) {
            re.push(jnum(z.real()));
            im.push(jnum(z.imag()));
        }
        o.set("re", re);
        o.set("im", im);
        cases.push(o);
        std::printf("  %-24s H1 %.6f V, H2 %.2f dBc, H3 %.2f dBc\n", name.c_str(), std::abs(h[0]),
                    20.0 * std::log10(std::abs(h[1]) / std::abs(h[0])),
                    20.0 * std::log10(std::abs(h[2]) / std::abs(h[0])));
    }
    root.set("cases", cases);
    std::string text, err;
    if (!json::write(root, text, err) || !write_file(dir + "/reference.json", text + "\n")) {
        std::fprintf(stderr, "cannot write %s/reference.json: %s\n", dir.c_str(), err.c_str());
        return 1;
    }
    return 0;
}

int spice_check(const std::string& dir, const std::string& ngspice, const std::string& work, int index,
                int expected_cases) {
    SpiceReference ref;
    std::string err;
    if (!read_spice_reference(dir + "/reference.json", ref, err)) {
        std::fprintf(stderr, "%s\n", err.c_str());
        return 1;
    }
    const auto cases = triode_spice_cases();
    if (expected_cases != static_cast<int>(cases.size())) {
        std::fprintf(stderr, "the build registers %d spice_triode_* tests, the harness has %zu cases; update "
                     "plugins/native/tube/CMakeLists.txt\n", expected_cases, cases.size());
        return 1;
    }
    if (index < 0 || static_cast<std::size_t>(index) >= cases.size() || ref.cases.size() != cases.size()) {
        std::fprintf(stderr, "case %d: the reference has %zu cases, the harness %zu\n", index, ref.cases.size(),
                     cases.size());
        return 1;
    }
    const SpiceCase& c = cases[static_cast<std::size_t>(index)];
    const std::string name = spice_case_name(c);
    int bad = 0;
    // The committed netlist is what the model's values generate today.
    const std::string netlist = triode_netlist(c, ref.timing, dsp::TriodeStageCircuit{}, dsp::TriodeDevice{});
    std::string committed;
    if (!read_file(dir + "/" + name + ".cir", committed) || committed != netlist) {
        std::fprintf(stderr, "FAIL %s.cir differs from the netlist the model's values generate; regenerate the "
                     "references (--spice-generate) in a deliberate commit\n", name.c_str());
        ++bad;
    }
    Harmonics h;
    std::vector<double> op;
    if (!run_ngspice(ngspice, work, netlist, err) || !read_op(work + "/op.txt", op, err) ||
        !spice_harmonics(work + "/out.txt", c.freq_hz, ref.timing.settle_s, ref.timing.settle_s + ref.timing.window_s,
                         h, err)) {
        std::fprintf(stderr, "FAIL %s: %s\n", name.c_str(), err.c_str());
        return 1;
    }
    // ngspice is deterministic on one build; a different version may move
    // the last digits. 1e-6 of the fundamental is -120 dB.
    const Harmonics& r = ref.harmonics[static_cast<std::size_t>(index)];
    double worst = 0.0;
    for (std::uint32_t k = 0; k < kSpiceHarmonics; ++k) worst = std::fmax(worst, std::abs(h[k] - r[k]));
    const double rel = worst / std::abs(r[0]);
    std::printf("%s: %s now vs the committed reference (%s): max |dH| / |H1| = %.3g (bar 1e-6)\n", name.c_str(),
                ngspice_version(ngspice, work).c_str(), ref.ngspice.c_str(), rel);
    if (!(rel <= 1e-6)) {
        std::fprintf(stderr, "FAIL %s: harmonics moved\n", name.c_str());
        ++bad;
    }
    double opd = 0.0;
    for (std::size_t i = 0; i < op.size(); ++i)
        opd = std::fmax(opd, std::fabs(op[i] - ref.op[static_cast<std::size_t>(index)][i]));
    if (!(opd <= 1e-6)) {
        std::fprintf(stderr, "FAIL %s: operating point moved by %.3g V\n", name.c_str(), opd);
        ++bad;
    }
    return bad == 0 ? 0 : 1;
}

