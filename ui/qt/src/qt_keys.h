// Qt key events to ui/keymap chords: ADR-0007 §5's chord_from_qt_key_event.
// It lives here rather than in ui/keymap because only ui/qt may include Qt
// (§1); everything after the chord -- resolving it through a profile,
// ensure_essentials(), the footer -- is ui/keymap's, unchanged.
//
// What a chord names, so nobody has to rediscover it:
//
//   - The digit row is named by the physical key, from its XKB keycode, on
//     every layout. A profile's "shift+3" is Shift held on the key with the
//     3 on it, which is the same key on US, AZERTY and ABNT2 keyboards; what
//     character that key types (#, ", or a dead key) does not matter. Read
//     from the character instead, AZERTY's unshifted "1/&" typed "&", which
//     a US reading calls shift+7: it armed track 7.
//   - Letters are named by the letter the layout puts on the key, so "z" is
//     the key with Z on it, on AZERTY too. That is what the tty sees and how
//     Windows names letter keys (virtual-key codes follow the layout). Only
//     when the layout puts no Latin letter there (Cyrillic, Greek) is the
//     letter read from the key's US position, as Windows does.
//   - Other punctuation is named by its character, read as a US layout
//     reads it -- exactly what KeyMap::chord_from_terminal_byte() does -- so
//     "+" is "plus" and "{" is shift+bracketleft.
//   - A key the decoder cannot place means nothing (Unrecognised), rather
//     than a guess: AltGr held (a profile has no way to name it), a dead key
//     off the digit row, a shifted-digit character such as "!" or "*" that
//     did not come from the digit row (AZERTY types both unshifted, on other
//     keys), and any digit at all when the platform's scan codes are not
//     XKB keycodes.
//   - Unlike the tty, Qt can tell the keypad apart (Qt::KeypadModifier), and
//     sees Super, which is "cmd". With Num Lock off the keypad still names
//     its digits: an engineer's keypad is a keypad.
//   - Auto-repeat is not a key press. Holding Space must not start and stop
//     takes at the repeat rate.
//
// The tty sees characters, not keys, so on a layout other than US it still
// reads them the US way (keymaps/README.md says where the two differ).
#pragma once

#include <QtGlobal>
#include <Qt>
#include <vector>

#include "sonora/keymap.h"

class QKeyEvent;
class QString;

namespace sonora::ui {

enum class QtKeyDecode {
    Chord,         // `out` holds the chord
    ModifierOnly,  // Shift, Ctrl, ... on their own: not a key press yet
    AutoRepeat,    // swallowed; the first press already did its job
    Unrecognised,  // a key no profile can name, or one the decoder cannot place
};

// One key press, as much of it as the decoder reads.
struct QtKeyInput {
    int key = 0;
    Qt::KeyboardModifiers mods = Qt::NoModifier;
    // The physical key's XKB keycode (the evdev code plus 8), or 0 when not
    // known. See qt_scan_codes_are_xkb().
    quint32 xkb_keycode = 0;
    // The XKB/X11 real-modifier mask, where AltGr shows as Mod5.
    quint32 xkb_mods = 0;
    bool auto_repeat = false;
};

// Whether QKeyEvent::nativeScanCode() is an XKB keycode on this platform.
// True for Qt's own xcb and Wayland plugins:
//   - xcb passes the X server's keycode. With the evdev keycodes every
//     current X server uses, that is the Linux evdev code plus 8; the older
//     xfree86 set agrees on every key read here (the typing block).
//   - Qt Wayland passes wl_keyboard's key plus 8. The protocol defines that
//     key as a Linux evdev code, and libxkbcommon defines keycodes as evdev
//     plus 8.
// Every other platform (eglfs, linuxfb, offscreen, ...) is not assumed, so
// there the digit row means nothing rather than something wrong.
bool qt_scan_codes_are_xkb(const QString& platform_name);

QtKeyInput qt_key_input(const QKeyEvent& e, bool scan_codes_are_xkb);

QtKeyDecode chord_from_qt_key(const QtKeyInput& in, KeyChord& out);

// Every chord the decoder above can produce, less the ones the kiosk
// compositor keeps for itself (Ctrl+Alt+F1..F12 switch virtual terminals in
// wlroots, and so in cage). It is to the window what
// KeyMap::terminal_chords() is to the tty: the device ensure_essentials()
// and the footer measure a profile against. Generated by running the decoder
// over its own input tables, so the two cannot disagree. Without XKB scan
// codes the digit row is not on the device, and ensure_essentials() says so.
std::vector<KeyChord> qt_device_chords(bool scan_codes_are_xkb);

}  // namespace sonora::ui
